def date(iso: str, lang: str) -> str:
    try:
        y, m, d = (int(x) for x in str(iso)[:10].split("-"))
    except Exception:
        return str(iso)
    if lang == "th":
        return f"{d} {_MON_TH[m - 1]} {y + 543}"
    if lang == "en":
        return f"{_MON_EN[m - 1]} {d}, {y}"
    if lang == "ko":
        return f"{y}년 {m}월 {d}일"
    return f"{y}年{m}月{d}日"


